// Packs the image-based button themes (assets/button-themes) for the build:
//   tools/pack_button_themes.swift <assets/button-themes> <out.c> <out-png-dir>
//
// Each theme folder holds {close,min,max}-{normal,hover,pressed,inactive}.{svg,png}.
// Every image is fitted into a square PNG and written twice:
//   - into a C file as byte arrays, compiled into libmactweak.dylib (sandboxed
//     apps cannot read files outside their container, so the core carries them);
//   - as PNG files for the settings app's previews.
// The order of `themes` gives the theme ids: 32, 33, ... (MT_THEME_IMAGE_BASE).
import AppKit

let themes = ["arc", "graphite", "orchis", "colloid", "nord", "fluent-square"]
let buttons = ["close", "min", "max"]
let states = ["normal", "hover", "pressed", "inactive"]
let side = 56

let args = CommandLine.arguments
let src = args[1], outC = args[2], outPNG = args[3]

func png(_ path: String) -> Data? {
    guard let image = NSImage(contentsOfFile: path) else { return nil }
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: side, pixelsHigh: side, bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                               bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSGraphicsContext.current!.imageInterpolation = .high
    let s = image.size
    let k = min(Double(side) / s.width, Double(side) / s.height)
    let w = s.width * k, h = s.height * k
    image.draw(in: NSRect(x: (Double(side) - w) / 2, y: (Double(side) - h) / 2, width: w, height: h))
    NSGraphicsContext.restoreGraphicsState()
    return rep.representation(using: .png, properties: [:])
}

var c = """
// Generated by tools/pack_button_themes.swift. Do not edit.
#include "button_themes.h"

"""
var table = "const mt_png mt_image_themes[\(themes.count)][3][4] = {\n"
for (t, theme) in themes.enumerated() {
    table += "  {\n"
    for (b, button) in buttons.enumerated() {
        table += "    {"
        for state in states {
            let base = "\(src)/\(theme)/\(button)-\(state)"
            let file = ["svg", "png"].map { "\(base).\($0)" }.first { FileManager.default.fileExists(atPath: $0) }
            guard let file, let data = png(file) else {
                table += "{0, 0}, "
                continue
            }
            let dir = "\(outPNG)/\(theme)"
            try? FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
            try! data.write(to: URL(fileURLWithPath: "\(dir)/\(button)-\(state).png"))
            let name = "t\(t)_b\(b)_\(state)"
            c += "static const unsigned char \(name)[] = {" + data.map { String($0) }.joined(separator: ",") + "};\n"
            table += "{\(name), \(data.count)}, "
        }
        table += "},\n"
    }
    table += "  },\n"
}
table += "};\nconst int mt_image_theme_count = \(themes.count);\n"
try! (c + "\n" + table).write(toFile: outC, atomically: true, encoding: .utf8)
print("packed \(themes.count) themes")
